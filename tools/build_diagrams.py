class Scene:
 def __init__(self,key,h,en=False):self.key=key;self.h=h;self.en=en;self.items=[]
 def t(self,x,y,ko,en=None,size=18,color=INK,bold=False):self.items.append(dict(kind='text',x=x,y=y,text=en if self.en and en else ko,size=size,color=color,bold=bold))
 def box(self,x,y,w,h,title,sub='',owned=False):
  self.items.append(dict(kind='rect',x=x,y=y,w=w,h=h,fill=SOFT if owned else '#ffffff',stroke=GREEN if owned else LINE,r=10))
  self.t(x+15,y+29,*title,size=19,bold=True)
  for i,s in enumerate(sub):self.t(x+15,y+56+i*22,*s,size=15,color=MUTED)
 def bg(self,x,y,w,h):self.items.append(dict(kind='rect',x=x,y=y,w=w,h=h,fill='#f7f9f6',stroke=LINE,r=12))
 def arrow(self,pts,color=GREEN,dashed=False):
  self.items.append(dict(kind='path',pts=pts,color=color,dashed=dashed))
  x,y=pts[-1];px,py=pts[-2];a=math.atan2(y-py,x-px);self.items.append(dict(kind='polygon',pts=[(x,y),(x-9*math.cos(a)+4*math.sin(a),y-9*math.sin(a)-4*math.cos(a)),(x-9*math.cos(a)-4*math.sin(a),y-9*math.sin(a)+4*math.cos(a))],color=color))
 def save(self):
  name=self.key+('-en' if self.en else '-ko');scenes[name]={'width':1000,'height':self.h,'items':self.items}
  parts=[f'<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="{self.h}" viewBox="0 0 1000 {self.h}" role="img"><title>{self.key} system architecture</title><rect width="1000" height="{self.h}" fill="#ffffff"/>']
  for e in self.items:
   k=e['kind']
   if k=='text':parts.append(f'<text x="{e["x"]}" y="{e["y"]}" font-family="Malgun Gothic,Arial,sans-serif" font-size="{e["size"]}" font-weight="{700 if e["bold"] else 400}" fill="{e["color"]}">{escape(e["text"])}</text>')
   elif k=='rect':parts.append(f'<rect x="{e["x"]}" y="{e["y"]}" width="{e["w"]}" height="{e["h"]}" rx="{e["r"]}" fill="{e["fill"]}" stroke="{e["stroke"]}" stroke-width="1.5"/>')
   elif k=='path':parts.append(f'<polyline points="{" ".join(f"{x},{y}" for x,y in e["pts"])}" fill="none" stroke="{e["color"]}" stroke-width="2.5" {"stroke-dasharray=\"7 5\"" if e["dashed"] else ""}/>')
   else:parts.append(f'<polygon points="{" ".join(f"{x},{y}" for x,y in e["pts"])}" fill="{e["color"]}"/>')
  parts.append('</svg>');(ROOT/f'assets/diagrams/{name}.svg').write_text('\n'.join(parts),encoding='utf-8')

